import { watch } from 'node:fs';
import { spawn } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
let server, building = false, dirty = false, timer;
function runBuild() {
  return new Promise(resolveBuild => {
    const child = spawn(process.execPath, ['scripts/build.mjs'], {cwd: root, stdio: 'inherit'});
    child.on('exit', code => resolveBuild(code === 0));
    child.on('error', () => resolveBuild(false));
  });
}
async function stopServer() {
  if (!server) return;
  const child = server; server = null;
  if (child.exitCode !== null) return;
  await new Promise(done => {child.once('exit', done); child.kill();});
}
async function rebuild() {
  if (building) {dirty = true; return;}
  building = true;
  if (await runBuild()) {
    await stopServer();
    server = spawn(process.execPath, ['scripts/serve.mjs'], {cwd: root, stdio: 'inherit'});
    console.log('已更新。浏览器刷新后查看修改。');
  } else console.error('构建失败，请修正后保存；上一次成功预览仍保留。');
  building = false;
  if (dirty) {dirty = false; queueRebuild();}
}
function queueRebuild() {clearTimeout(timer);timer = setTimeout(rebuild, 250);}
const watchers = ['web', 'server', 'docs'].map(folder => watch(resolve(root, folder), (_, filename) => {
  // data.js is generated by build; watching it would cause an endless rebuild.
  if (filename && !(folder === 'web' && filename === 'data.js')) queueRebuild();
}));
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, async () => {clearTimeout(timer);watchers.forEach(w => w.close());await stopServer();process.exit(0);});
await rebuild();
